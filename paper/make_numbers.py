def write_stage1_ablations(s1: dict, s1_cfg: dict) -> None:
    base_cfg = s1_cfg['Full']
    groups = [
        ('Reference', [('Full', 'polar, learned prior, offsets')]),
        ('Column decoder', [('PriorNone', 'no ground-plane prior'), ('PriorFixed', 'fixed prior'),
                            ('NoOffsets', 'no learned offsets')]),
        ('Cross-view mapping', [('Dense', 'dense mapping (no polar)')]),
        ('Input', [('Crop', r'centre \num{224} crop'), ('Vgg', 'frozen VGG-16')]),
        ('Head and loss', [('HiRes', r'native $\SOneHiResOutH\times\SOneHiResOutW$ head'),
                           ('ClassW', 'class-weighted loss')]),
    ]
    ref = s1['Full']['test_full_res']
    all_runs = [t for _, g in groups for t, _ in g]
    all_miou = [s1[t]['test_full_res']['miou'] for t in all_runs]
    all_cls = {cls: [s1[t]['test_full_res']['iou'][cls] for t in all_runs] for cls, _ in CLASSES}
    notes = []
    body = []
    for gname, items in groups:
        body.append(r'\multicolumn{8}{l}{\emph{' + gname + r'}} \\')
        for tok, desc in items:
            t = s1[tok]['test_full_res']
            extra = []
            cfg = s1_cfg[tok]
            if bool(cfg.get('amp')) != bool(base_cfg.get('amp')):
                extra.append('AMP ' + ('on' if cfg.get('amp') else 'off'))
            if cfg.get('batch_size') != base_cfg.get('batch_size'):
                extra.append(f"batch {cfg['batch_size']}")
            mark = ''
            if extra:
                sym = ['*', r'\dagger', r'\ddagger', r'\S'][len(notes)]
                mark = f'$^{{{sym}}}$'
                notes.append(f'$^{{{sym}}}$Also differs from the reference in: ' + ', '.join(extra) + '.')
            delta = '---' if tok == 'Full' else num(t['miou'] - ref['miou'], 3, sign=True)
            cells = [r'\quad ' + desc + mark,
                     num(s1[tok]['params_trainable'] / 1e6, 2),
                     best_num(t['miou'], all_miou, 3),
                     delta]
            cells += [best_num(t['iou'][cls], all_cls[cls], 3) for cls, _ in CLASSES]
            body.append(' & '.join(cells) + r' \\')
        if gname != groups[-1][0]:
            body.append(r'\addlinespace')
    note_txt = (' ' + ' '.join(notes)) if notes else ''
    tex = HEADER + r'''\begin{table}[t]
  \centering
  \small
  \caption{Stage 1 single-change ablations on the CVUSA test set (\NTest{} pairs, SegFormer pseudo-labels).
  The reference uses frozen DINOv2-S/14 features of the full aerial tile, polar mapping, the learned
  ground-plane prior, learned offsets and a $\SOneOutH\times\SOneOutW$ head; each other row changes one of these.
  $\Delta$ is the mIoU change relative to the reference run. Each row is one training run with one seed,
  so differences of a few thousandths are within run-to-run noise we did not measure. Best value per column
  in bold.''' + note_txt + r'''}
  \label{tab:stage1_ablations}
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{l c cc cccc}
    \toprule
    Variant & Params (M) & mIoU$\uparrow$ & $\Delta$ & Sky & Veg. & Road & Bldg. \\
    \midrule
''' + '\n'.join('    ' + b for b in body) + r'''
    \bottomrule
  \end{tabular}
\end{table}
'''
    write(os.path.join(TABLES, 'stage1_ablations.tex'), tex)


def write_stage2_ladder(metrics: dict, pc: dict) -> None:
    gen = {'A': 'Pix2Pix U-Net', 'B': 'SPADE', 'C': 'SPADE', 'D': 'SPADE + aerial', 'E': 'SPADE + aerial'}
    blocks = [('Oracle layout', ['A', 'B', 'D']), ('Predicted layout (end-to-end)', ['C', 'E'])]
    cols = [  # (bootstrap key, metrics key, dp, higher_is_better, has_ci)
        ('ssim', 'mean_ssim', 3, True, True), ('psnr', 'mean_psnr', 2, True, True),
        ('lpips', 'mean_lpips', 3, False, True), ('sd', 'mean_sd', 0, False, True),
        (None, 'fid_clean', 1, False, False), (None, 'kid_clean', 3, False, False),
    ]
    body = []
    for bname, keys in blocks:
        body.append(r'\multicolumn{8}{l}{\emph{' + bname + r'}} \\')
        for k in keys:
            m = metrics[k]
            if m['aux_aerial'] != ('aerial' in gen[k]):
                raise SystemExit(f'Config {k}: aux_aerial={m["aux_aerial"]} disagrees with label {gen[k]!r}')
            cells = [k, gen[k]]
            ci = ['', '']
            for bk, mk, dp, hib, has_ci in cols:
                cells.append(best_num(m[mk], [metrics[j][mk] for j in keys], dp, hib))
                if has_ci:
                    lo, hi = pc[k][bk]['ci95_low'], pc[k][bk]['ci95_high']
                    ci.append(r'{\scriptsize[' + num(lo, dp) + ', ' + num(hi, dp) + ']}')
                else:
                    ci.append('')
            body.append(' & '.join(cells) + r' \\')
            body.append(' & '.join(ci) + r' \\[2pt]')
        if bname != blocks[-1][0]:
            body.append(r'\midrule')
    tex = HEADER + r'''\begin{table}[t]
  \centering
  \small
  \setlength{\tabcolsep}{4pt}
  \caption{Stage 2 synthesis ladder (Configs A--E) on the CVUSA test set (\NTest{} pairs, $\GanImgH\times\GanImgW$).
  Oracle rows use the ground-truth segmentation of the target panorama as layout; predicted rows use the
  Stage 1 output. ``+ aerial'' adds the warped aerial image as extra conditioning. Small type gives 95\% bootstrap confidence intervals over images (\NBoot{} resamples);
  they do not capture training-seed variance. clean-FID and KID are set-level scores without intervals.
  Sharp.\ gap is our Laplacian sharpness gap. Bold marks the best point estimate per block (ties at the
  displayed precision are all bold) and does not by itself imply a significant difference; paired tests
  are in \Cref{tab:paired_diffs}.}
  \label{tab:stage2_ladder}
  \begin{tabular}{c l cccc cc}
    \toprule
    Cfg & Generator & SSIM$\uparrow$ & PSNR$\uparrow$ & LPIPS$\downarrow$ & Sharp.\ gap$\downarrow$ & clean-FID$\downarrow$ & KID$\downarrow$ \\
    \midrule
''' + '\n'.join('    ' + b for b in body) + r'''
    \bottomrule
  \end{tabular}
\end{table}
'''
    write(os.path.join(TABLES, 'stage2_ladder.tex'), tex)


def write_paired(paired: dict, fid: dict) -> None:
    rows = [
        ('D_minus_B', r'D $-$ B', 'oracle', fid['D'] - fid['B']),
        ('E_minus_C', r'E $-$ C', 'predicted', fid['E'] - fid['C']),
    ]
    body = []
    for key, label, lay, dfid in rows:
        cells, ci = [label, lay], ['', '']
        for met, dp in (('ssim', 5), ('psnr', 2), ('lpips', 3)):
            d = paired[key][met]
            excl = d['ci95_low'] > 0 or d['ci95_high'] < 0
            cells.append(num(d['mean_diff'], dp, sign=True) + (r'$^\dagger$' if excl else ''))
            ci.append(r'{\scriptsize[' + num(d['ci95_low'], dp, sign=True) + ', '
                      + num(d['ci95_high'], dp, sign=True) + ']}')
        cells.append(num(dfid, 1, sign=True))
        ci.append('')
        body.append(' & '.join(cells) + r' \\')
        body.append(' & '.join(ci) + r' \\[2pt]')
    tex = HEADER + r'''\begin{table}[t]
  \centering
  \small
  \caption{Effect of warped-aerial conditioning: paired per-image differences (with aerial minus without)
  on the same \NTest{} test images. Small type gives paired 95\% bootstrap intervals (\NBoot{} resamples over
  images, seed \BootSeed). $^\dagger$: interval excludes zero. Higher is better for SSIM and PSNR, lower for
  LPIPS and clean-FID. The clean-FID difference is a set-level point estimate without an interval.}
  \label{tab:paired_diffs}
  \begin{tabular}{l l ccc c}
    \toprule
    Pair & Layout & $\Delta$SSIM & $\Delta$PSNR (dB) & $\Delta$LPIPS & $\Delta$clean-FID \\
    \midrule
''' + '\n'.join('    ' + b for b in body) + r'''
    \bottomrule
  \end{tabular}
\end{table}
'''
    write(os.path.join(TABLES, 'paired_diffs.tex'), tex)


def write_compute(rows: list, s1_h: float, s2_h: float, eval_h: float) -> None:
    body = []
    notes = []
    for stage in ('1', '2'):
        body.append(r'\multicolumn{6}{l}{\emph{Stage ' + stage + r'}} \\')
        for st, run, purpose, gpu, ep, h, pm, note in rows:
            if st != stage:
                continue
            mark = ''
            if note:
                mark = '$^{' + 'abcdef'[len(notes)] + '}$'
                notes.append(mark + note)
            run_tt = r'\texttt{' + run.replace('_', r'\_') + '}'
            body.append(' & '.join([run_tt, purpose, gpu, ep, r'\num{' + h + '}' + mark,
                                    r'\num{' + pm + '}']) + r' \\')
        body.append(r'\addlinespace')
    body.append(r'\multicolumn{6}{l}{\emph{Evaluation}} \\')
    body.append(r'\texttt{final\_eval} & Configs A--E & '
                r'\todo{GPU?} & --- & \num{' + fnum(eval_h, 2) + r'} & --- \\')
    body.append(r'\midrule')
    body.append(r'\multicolumn{4}{l}{Total logged (Stage 1 / Stage 2 / evaluation)} & \multicolumn{2}{l}{\num{'
                + fnum(s1_h, 1) + r'} / \num{' + fnum(s2_h, 1) + r'} / \num{' + fnum(eval_h, 1) + r'}} \\')
    for n_ in notes:
        body.append(r'\multicolumn{6}{p{0.95\linewidth}}{\scriptsize ' + n_ + r'} \\')
    tex = HEADER + r'''\begin{table}[t]
  \centering
  \footnotesize
  \setlength{\tabcolsep}{3pt}
  \caption{Compute per run, in wall-clock GPU-hours on a single GPU. Stage 1 times come from each run's
  \texttt{results.json}; Stage 2 times are the sum of per-epoch times printed in \texttt{logs/}. Crashed
  and restarted attempts are not counted. Evaluation time excludes clean-FID/KID computation. GPUs differ
  between runs, so hours are not directly comparable. Params are trainable parameters (Stage 1) or
  generator parameters (Stage 2; the discriminator adds \DiscParams{}M).}
  \label{tab:compute}
  \begin{tabular}{l p{0.24\linewidth} l c c c}
    \toprule
    Run & Purpose & GPU & Epochs & GPU-h & Params (M) \\
    \midrule
''' + '\n'.join('    ' + b for b in body) + r'''
    \bottomrule
  \end{tabular}
\end{table}
'''
    write(os.path.join(TABLES, 'compute.tex'), tex)


