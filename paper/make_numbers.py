def find_final_eval_dir() -> str:
    for cand in FINAL_EVAL_CANDIDATES:
        ok = os.path.isfile(p(cand, 'bootstrap_ci.json'))
        for slug in CONFIG_SLUGS.values():
            mp = p(cand, f'{slug}_metrics.json')
            if not os.path.isfile(mp):
                ok = False
                break
            with open(mp, encoding='utf-8') as f:
                m = json.load(f)
            if m.get('smoke') or m.get('n_images') != 8884 or 'fid_clean' not in m:
                ok = False
                break
        if ok:
            return cand
        print(f'[i] skipping {cand}: missing files or smoke / partial run')
    raise SystemExit('No complete final_eval directory found (need 5 full metrics JSONs + bootstrap_ci.json)')


def parse_gan_log(fname: str) -> dict:
    with open(p('logs', fname), encoding='utf-8', errors='replace') as f:
        text = f.read()
    out: dict = {}
    gpus = re.findall(r'\[\*\] GPU\s*:\s*(.+?)\s+\(', text)
    out['gpu'] = gpus[-1] if gpus else None
    amps = re.findall(r'\[\*\] AMP\s*:\s*(ON|OFF)', text)
    out['amp'] = amps[-1] if amps else None
    gs = re.findall(r'G updates / D\s*:\s*(\d+)', text)
    out['g_steps'] = int(gs[-1]) if gs else None
    out['warm_d'] = bool(re.search(r'Resumed D (weights only|from checkpoint)', text))
    out['random_d'] = 'Discriminator: random init' in text
    gp = re.findall(r'Generator params\s*:\s*([\d.]+)\s*M', text)
    out['g_params_m'] = float(gp[-1]) if gp else None
    dp_ = re.findall(r'Discriminator params\s*:\s*([\d.]+)\s*M', text)
    out['d_params_m'] = float(dp_[-1]) if dp_ else None
    l1 = re.findall(r'^\s*lambda_l1\s+([\d.]+)', text, flags=re.M)
    out['lambda_l1'] = float(l1[-1]) if l1 else None
    perc = re.findall(r'VGG perceptual loss weight:\s*([\d.]+)', text)
    out['lambda_perc'] = float(perc[-1]) if perc else None
    ls = re.findall(r'^\s*label_smooth\s+([\d.]+)', text, flags=re.M)
    out['label_smooth'] = float(ls[-1]) if ls else None
    ep = re.findall(r'^\s*epochs\s+(\d+)', text, flags=re.M)
    out['epochs_cfg'] = int(ep[-1]) if ep else None
    bs = re.findall(r'^\s*batch_size\s+(\d+)', text, flags=re.M)
    out['batch_size'] = int(bs[-1]) if bs else None
    lr = re.findall(r'^\s*lr\s+([\d.eE-]+)', text, flags=re.M)
    out['lr'] = float(lr[-1]) if lr else None
    ckpt_dirs = set(re.findall(r'^\s*ckpt_dir\s+(\S+)', text, flags=re.M))
    resumes = set(re.findall(r'^\s*resume_g\s+(\S+)', text, flags=re.M))
    out['self_resumed'] = any(r.startswith(cd) for r in resumes for cd in ckpt_dirs)
    hb = re.search(r'D_loss in \[([\d.]+)\D+?([\d.]+)\]', text)
    out['healthy_d'] = (float(hb.group(1)), float(hb.group(2))) if hb else None

    epochs = OrderedDict()
    for m in re.finditer(
        r'\[epoch (\d+) done\]\s+avg G=([\d.]+)\s+avg D=([\d.]+)\s+time=([\d.]+) min', text,
    ):
        epochs[int(m.group(1))] = {
            'avg_g': float(m.group(2)), 'avg_d': float(m.group(3)), 'min': float(m.group(4)),
        }
    out['epochs'] = epochs

    steps: dict[int, bool] = {}
    for m in re.finditer(r'step (\d+)\s+G=.*?D=([\d.]+)\[([^\]]*)\]', text):
        steps[int(m.group(1))] = m.group(3) == 'D_weak'
    out['n_step_lines'] = len(steps)
    out['d_weak_frac'] = (sum(steps.values()) / len(steps)) if steps else None

    diag = re.search(
        r'\[D_diag run_step\s+1 [^\]]*\].*?real\(mean/min/max\)=([-\d.]+)/.*?fake\(mean/min/max\)=([-\d.]+)/',
        text,
    )
    out['diag_step1'] = (float(diag.group(1)), float(diag.group(2))) if diag else None
    return out


