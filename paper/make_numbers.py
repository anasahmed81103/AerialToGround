# ----------------------------------------------------------------------------- helpers

def p(*parts: str) -> str:
    return os.path.join(ROOT, *parts)


def load_json(*parts: str) -> dict:
    with open(p(*parts), encoding='utf-8') as f:
        return json.load(f)


def warn(msg: str) -> None:
    _warnings.append(msg)
    print(f'[!] {msg}', file=sys.stderr)


def fnum(x: float, dp: int, sign: bool = False) -> str:
    """Fixed-point string; never prints '-0.000'."""
    if x is None or (isinstance(x, float) and math.isnan(x)):
        raise ValueError('missing number')
    s = f'{x:+.{dp}f}' if sign else f'{x:.{dp}f}'
    if float(s) == 0.0:
        s = ('+' if sign else '') + f'{0:.{dp}f}'
    return s


def num(x: float, dp: int, sign: bool = False) -> str:
    return r'\num{' + fnum(x, dp, sign) + '}'


def define(name: str, value: str) -> str:
    if not re.fullmatch(r'[A-Za-z]+', name):
        raise ValueError(f'invalid macro name {name!r} (letters only)')
    if name in _macros:
        raise ValueError(f'duplicate macro {name}')
    _macros[name] = value
    return value


def dnum(name: str, x: float, dp: int, sign: bool = False) -> str:
    return define(name, num(x, dp, sign))


def short_gpu(name: str | None) -> str:
    if not name:
        return TODO + '{GPU?}'
    return name.replace('NVIDIA ', '').replace('GeForce ', '').strip()


def bold_if(s: str, cond: bool) -> str:
    return r'\textbf{' + s + '}' if cond else s


def best_num(x: float, values: list[float], dp: int, higher: bool = True) -> str:
    """\\num{x}, bold if it ties the best value at the displayed precision."""
    rounded = [float(fnum(v, dp)) for v in values]
    best = max(rounded) if higher else min(rounded)
    return bold_if(num(x, dp), float(fnum(x, dp)) == best)


def write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'[*] wrote {os.path.relpath(path, ROOT)}')


