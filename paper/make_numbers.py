    s1_gpu = {'Full': p2['training'].get('gpu'), 'HiRes': p2['polar_full_64x320']['training'].get('gpu')}
    s1_purpose = {
        'Full': 'reference', 'PriorNone': 'no prior', 'PriorFixed': 'fixed prior',
        'NoOffsets': 'no offsets', 'Dense': 'dense mapping',
        'Crop': r'\num{224} crop', 'Vgg': 'VGG-16',
        'HiRes': r'$\SOneHiResOutH\times\SOneHiResOutW$ head', 'ClassW': 'class weights',
    }
    s1_hours = 0.0
    for tok, r in s1.items():
        h = r['train_minutes'] / 60
        s1_hours += h
        dnum(f'GpuHoursSOne{tok}', h, 2)
        define(f'GpuNameSOne{tok}', short_gpu(s1_gpu.get(tok)))
        compute_rows.append(('1', STAGE1_RUNS[tok], s1_purpose[tok], short_gpu(s1_gpu.get(tok)),
                             str(s1_cfg[tok]['epochs']), fnum(h, 2), fnum(r['params_trainable'] / 1e6, 2), ''))
    dnum('GpuHoursSOneTotal', s1_hours, 1)

    s2_hours = 0.0
    for tok, (fn, purpose) in GAN_LOGS.items():
        lg = logs[tok]
        h = sum(e['min'] for e in lg['epochs'].values()) / 60
        s2_hours += h
        n_ep = len(lg['epochs'])
        dnum(f'GpuHours{tok}', h, 2)
        define(f'GpuName{tok}', short_gpu(lg['gpu']))
        define(f'EpochsLogged{tok}', str(n_ep))
        note = ''
        if lg['self_resumed'] and lg['epochs']:
            note = (r'\texttt{' + fn.replace('.txt', '').replace('_', r'\_') + '}: '
                    + TODO + '{epochs before ' + str(min(lg['epochs'])) + ' were not timed in the log; '
                    'their GPU-hours are missing from this row and from the total}')
        compute_rows.append(('2', fn.replace('.txt', ''), purpose, short_gpu(lg['gpu']),
                             str(n_ep), fnum(h, 2), fnum(lg['g_params_m'], 1), note))
    dnum('GpuHoursSTwoLogged', s2_hours, 1)

    eval_h = sum(metrics[k]['elapsed_sec'] for k in CONFIG_KEYS) / 3600
    dnum('EvalHoursNoFid', eval_h, 2)
    dnum('GpuHoursTotalLogged', s1_hours + s2_hours + eval_h, 1)

    # ================================================================= write numbers.tex
    lines = [HEADER, '% Sources: experiments/results_table.json, experiments/phase2/runs/*/results.json,\n',
             f'%          {fe_dir.replace(os.sep, "/")}/*_metrics.json + bootstrap_ci.json, logs/*.txt\n\n']
    for name, val in _macros.items():
        lines.append(f'\\newcommand{{\\{name}}}{{{val}}}\n')
    write(os.path.join(PAPER, 'numbers.tex'), ''.join(lines))

    # ================================================================= tables
    write_stage1_main(s1, crossnet, phase1)
    write_stage1_ablations(s1, s1_cfg)
    write_stage2_ladder(metrics, pc)
    write_paired(paired, fid)
    write_compute(compute_rows, s1_hours, s2_hours, eval_h)

    print('\n=== macros (%d) ===' % len(_macros))
    w = max(len(n) for n in _macros)
    for name, val in _macros.items():
        print(f'\\{name:<{w}}  {val}')
    if _warnings:
        print(f'\n=== {len(_warnings)} warning(s) ===')
        for x in _warnings:
            print(' -', x)


